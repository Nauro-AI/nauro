# --- Content-conditional regen: unchanged content skips the write ---


def _doctor_timestamp(agents_md: Path, stale_stamp: str) -> str:
    """Rewrite the header timestamp line to ``stale_stamp``; return new content."""
    doctored = "\n".join(
        stale_stamp if line.startswith(HEADER_MARKER) else line
        for line in agents_md.read_text().split("\n")
    )
    agents_md.write_text(doctored)
    return doctored


def test_regen_skips_write_when_content_unchanged(tmp_path: Path):
    """A regen with no store change leaves the file byte-identical.

    The stale timestamp surviving proves the write was skipped rather than
    re-emitted with a fresh stamp - prompt caches keyed on file bytes stay warm.
    Skipped repos are not reported as updated and the bridge sink stays empty
    (the bridge is write-coupled by design).
    """
    from nauro.store.registry import register_project_v2

    repo = tmp_path / "repo"
    repo.mkdir()
    pid, store = register_project_v2("myproj", [repo])
    scaffold_project_store("myproj", store)
    regenerate_agents_md_for_project(pid, store)
    agents_md = repo / "AGENTS.md"
    stale_stamp = f"{HEADER_MARKER}2020-01-01T00:00:00Z). -->"
    doctored = _doctor_timestamp(agents_md, stale_stamp)

    bridge_outcomes: list = []
    updated = regenerate_agents_md_for_project(
        pid, store, overwrite_unmanaged=True, bridge_sink=bridge_outcomes
    )

    assert updated == []
    assert bridge_outcomes == []
    assert agents_md.read_text() == doctored


def test_regen_reclaims_unmanaged_file_missing_only_the_marker_line(tmp_path: Path):
    """A file that lost only its header marker line is rewritten, not skipped.

    Masking blanks the marker line, so without the managed-file gate an
    otherwise byte-identical file whose marker was replaced by a blank line
    would wrongly mask equal to fresh content and the overwrite path could
    never restore the marker.
    """
    from nauro.store.registry import register_project_v2

    repo = tmp_path / "repo"
    repo.mkdir()
    pid, store = register_project_v2("myproj", [repo])
    scaffold_project_store("myproj", store)
    regenerate_agents_md_for_project(pid, store)
    agents_md = repo / "AGENTS.md"
    demoted = "\n".join(
        "" if line.startswith(HEADER_MARKER) else line for line in agents_md.read_text().split("\n")
    )
    agents_md.write_text(demoted)

    bridge_outcomes: list = []
    updated = regenerate_agents_md_for_project(
        pid, store, overwrite_unmanaged=True, bridge_sink=bridge_outcomes
    )

    assert updated == [repo]
    assert len(bridge_outcomes) == 1
    assert HEADER_MARKER in agents_md.read_text()


def test_regen_store_change_writes_and_refreshes_timestamp(tmp_path: Path):
    """A real store change still writes, refreshing content and timestamp."""
    from nauro.store.registry import register_project_v2

    repo = tmp_path / "repo"
    repo.mkdir()
    pid, store = register_project_v2("myproj", [repo])
    scaffold_project_store("myproj", store)
